export function renderBuiltinSkill(definition: BuiltinSkillDefinition): string {
  return [
    "---",
    `id: ${definition.id}`,
    `name: ${definition.id}`,
    "version: 1.0.0",
    `description: ${JSON.stringify(definition.description)}`,
    "permissions: []",
    "entry: instruction",
    "---",
    "",
    `# ${definition.title}`,
    "",
    definition.body,
    ""
  ].join("\n");
}

export function isBuiltinSkillId(value: unknown): value is BuiltinSkillId {
  return typeof value === "string"
    && (BUILTIN_SKILL_IDS as readonly string[]).includes(value);
}

export function getBuiltinSkillDefinition(
  value: unknown
): BuiltinSkillDefinition | null {
  return isBuiltinSkillId(value)
    ? BUILTIN_SKILLS.find((definition) => definition.id === value) ?? null
    : null;
}
